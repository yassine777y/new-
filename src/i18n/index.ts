export const DICTS: Record<Lang, Dict> = { en, fr, ar }

/** Translate a key, falling back to English and finally to the key itself. */
export function translate(lang: Lang, key: I18nKey, vars?: Record<string, string | number>): string {
  let out = DICTS[lang]?.[key] ?? en[key] ?? String(key)
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v))
  return out
}

/** Text direction for a language. */
export const dirFor = (lang: Lang): 'ltr' | 'rtl' => LANG_META[lang].dir

/** BCP-47 tag used for speech recognition and synthesis. */
export const speechLangFor = (lang: Lang): string => LANG_META[lang].speech

/** Which keys are still untranslated — handy to keep the dictionaries honest. */
export function missingKeys(lang: Lang): I18nKey[] {
  return (Object.keys(en) as I18nKey[]).filter((k) => !DICTS[lang]?.[k])
}

