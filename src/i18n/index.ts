/**
 * Interface languages.
 *
 * A deliberately small i18n: one dictionary per language, one `t()` helper, no dependency.
 * Keys are typed against the English dictionary, and any language may omit a key — the
 * English string is the fallback, so the UI is never blank and never shows a raw key.
 *
 * Scope: the interface chrome — navigation, headings, buttons, control labels, hints and the
 * accessibility panel. The *content* stays in the language of its publisher on purpose:
 * dataset descriptions, source titles and licence notes quote NASA, NOAA, NSIDC and the IPCC,
 * and translating them would misrepresent the citation. The voice agent is the exception: it
 * already answers in Darija when you speak Darija, and it speaks the interface language aloud.
 */

